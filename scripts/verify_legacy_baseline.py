"""Read back a legacy baseline and generate a compact diagnostic projection."""
import argparse
import json
from pathlib import Path

import h5py
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.collections import LineCollection


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--run', required=True, type=Path)
    args = p.parse_args()
    run = args.run.resolve()
    report = json.loads((run / 'run-report.json').read_text())
    if report['status'] not in ('completed', 'stopped_memory_guard'):
        raise RuntimeError(f"Unsupported run status: {report['status']}")
    # These pickle-bearing files were generated by our own local baseline run.
    with np.load(run / 'macaque_original_isotropy_skeleton.npz', allow_pickle=True) as f:
        skels = f['skeletons'].item()
    with np.load(run / 'macaque_stats.npz', allow_pickle=True) as f:
        branches = f['branch_info'].tolist()
        total_length = float(f['total_length'])
    verification = {'run_status': report['status'], 'branches': len(branches), 'legacy_total_length_nm': total_length,
                    'skeletons': len(skels), 'checks': {}, 'label_counts': {}}
    dense_path = run / 'down_branch_macaque_vessels.h5'
    has_dense = dense_path.exists()
    verification['dense_segmentation_written'] = has_dense
    checked_path = dense_path if has_dense else run / 'macaque_skel_as_array.h5'
    verification['checked_volume'] = checked_path.name
    counts = np.zeros(256, dtype=np.int64)
    selected = outside = missing = 0
    projections = None
    with h5py.File(report['input'], 'r') as src, h5py.File(checked_path, 'r') as dst:
        a, b = src['main'], dst['main']
        if a.shape != b.shape:
            raise AssertionError('Output shape differs from input')
        verification['shape'] = list(b.shape)
        verification['dtype'] = str(b.dtype)
        projections = [np.zeros((a.shape[1], a.shape[2]), bool),
                       np.zeros((a.shape[0], a.shape[2]), bool),
                       np.zeros((a.shape[0], a.shape[1]), bool)]
        for z in range(0, a.shape[0], 16):
            mask = a[z:z+16] == 1
            out = b[z:z+16]
            selected += int(mask.sum())
            outside += int(np.count_nonzero((out != 0) & ~mask))
            missing += int(np.count_nonzero((out == 0) & mask))
            counts += np.bincount(out.ravel(), minlength=256)
            projections[0] |= mask.any(axis=0)
            projections[1][z:z+16] = mask.any(axis=1)
            projections[2][z:z+16] = mask.any(axis=2)
    verification['label_counts'] = {str(i): int(n) for i, n in enumerate(counts) if n}
    verification['checks'] = {'selected_input_voxels': selected, 'nonzero_outside_label_1': outside,
                              'nonzero_output_voxels': int(counts[1:].sum()),
                              'unassigned_label_1_voxels': missing if has_dense else None,
                              'branch_ids_fit_output_dtype': len(branches) <= 255 if has_dense else None,
                              'foreground_mask_preserved': outside == 0 and missing == 0 if has_dense else None}
    sz, sy, sx = report['spacing_zyx_nm']
    shape = verification['shape']
    fig, axes = plt.subplots(1, 3, figsize=(15, 5))
    for ax, bg, (xaxis, yaxis), (w, h), title in zip(
        axes, projections, [(2, 1), (2, 0), (1, 0)],
        [(shape[2]*sx, shape[1]*sy), (shape[2]*sx, shape[0]*sz), (shape[1]*sy, shape[0]*sz)],
        ['XY projection', 'XZ projection', 'YZ projection'],
    ):
        ax.imshow(bg, cmap='Greys', alpha=.4, origin='lower', extent=[0, w/1000, 0, h/1000])
        for skel in skels.values():
            segments = skel.vertices[skel.edges][:, :, [xaxis, yaxis]] / 1000
            ax.add_collection(LineCollection(segments, colors='#cc3333', linewidths=.65))
        ax.set_title(title)
        ax.set_xlabel('micrometers')
        ax.set_ylabel('micrometers')
        ax.set_aspect('equal')
    fig.suptitle('Legacy macaque baseline: vessel mask (gray), raw skeleton (red)\nProjection overlaps do not establish connectivity or skeleton accuracy')
    fig.tight_layout()
    fig.savefig(run / 'skeleton-preview.png', dpi=160)
    plt.close(fig)
    (run / 'verification.json').write_text(json.dumps(verification, indent=2) + '\n')
    print(json.dumps({k:v for k,v in verification.items() if k != 'label_counts'}, indent=2))


if __name__ == '__main__':
    main()
